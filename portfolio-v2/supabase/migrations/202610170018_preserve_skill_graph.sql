insert into portfolio_api.skill_connections(category_id,source_skill,target_skill,position)
select c.id,e.source_skill,e.target_skill,e.position from portfolio_api.skill_categories c join portfolio_api.skill_categories_names n on n.skill_categorie_id=c.id join edges e on e.source_skill=n.item_text
where exists(select 1 from portfolio_api.skill_categories_names other join portfolio_api.skill_categories category on category.id=other.skill_categorie_id where other.item_text=e.target_skill and category.revision_kind=c.revision_kind)
on conflict do nothing;
